/* ─── Движок i18n ─── */
(function () {
  var DICT = window.RAVIO_LANG_LANDING.kz;
  var SKIP = { SCRIPT: 1, STYLE: 1, NOSCRIPT: 1, SVG: 1, PATH: 1, svg: 1, path: 1 };
  var pairs = []; // { node, ru }  — только текстовые узлы, попавшие в словарь
  var LANG = "ru";

  function norm(s) { return s.replace(/\s+/g, " ").trim(); }

  function collect() {
    // Исключаем только JS-обновляемые узлы hero-виджета (их текст переставляет
    // свой JS по таймеру). Статичные подписи виджета переводятся как обычно.
    var excluded = [];
    document.querySelectorAll("#wArea, #wFrom, #wTo, #wM2, #wStages, [data-no-i18n]").forEach(function (el) { excluded.push(el); });
    function isExcluded(n) { for (var i = 0; i < excluded.length; i++) if (excluded[i].contains(n)) return true; return false; }
    function walk(n) {
      for (var i = 0; i < n.childNodes.length; i++) {
        var ch = n.childNodes[i];
        if (ch.nodeType === 3) {
          var t = norm(ch.nodeValue);
          if (t && DICT[t] && !isExcluded(ch)) pairs.push({ node: ch, ru: ch.nodeValue });
        } else if (ch.nodeType === 1 && !SKIP[ch.tagName]) {
          walk(ch);
        }
      }
    }
    walk(document.body);
  }

  function apply(lang) {
    LANG = lang;
    pairs.forEach(function (p) {
      if (lang === "kz") {
        var t = norm(p.ru);
        var kz = DICT[t];
        if (kz) p.node.nodeValue = p.ru.replace(t, kz);
      } else {
        p.node.nodeValue = p.ru;
      }
    });
    document.documentElement.setAttribute("lang", lang === "kz" ? "kk" : "ru");
    // подсветить активную кнопку
    document.querySelectorAll("[data-lang-btn]").forEach(function (b) {
      b.classList.toggle("active", b.getAttribute("data-lang-btn") === lang);
    });
    try { localStorage.setItem("ravio_lang", lang); } catch (e) {}
  }

  function init() {
    collect();
    var saved = "ru";
    try { saved = localStorage.getItem("ravio_lang") || "ru"; } catch (e) {}
    apply(saved === "kz" ? "kz" : "ru");
    document.querySelectorAll("[data-lang-btn]").forEach(function (b) {
      b.addEventListener("click", function () { apply(b.getAttribute("data-lang-btn")); });
    });
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init);
  else init();
})();
